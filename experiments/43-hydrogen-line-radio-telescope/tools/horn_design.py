#!/usr/bin/env python3
"""Design a pyramidal horn for the 21 cm hydrogen line (1420.405751768 MHz).

    python3 horn_design.py                 # 17 dBi horn on a WR-650 feed, prints dimensions, writes files
    python3 horn_design.py --gain 15       # smaller horn

Method: the optimum-gain pyramidal horn design procedure of C. A. Balanis, *Antenna Theory*
(ch. 13, "Pyramidal horn - design procedure"). Given the desired gain G0 and the feed waveguide
(a x b), solve for chi:

  (sqrt(2 chi) - b/l)^2 (2 chi - 1) = (G0/(2 pi) sqrt(3/(2 pi)) / sqrt(chi) - a/l)^2 (G0^2/(6 pi^3) / chi - 1)

then  rho_e = chi l,  rho_h = G0^2 / (8 pi^3 chi) l,  a1 = sqrt(3 l rho_h),  b1 = sqrt(2 l rho_e),
      p_e = (b1 - b) sqrt((rho_e/b1)^2 - 1/4),  p_h = (a1 - a) sqrt((rho_h/a1)^2 - 1/4)   (must be equal)

The feed is a rectangular waveguide excited by a quarter-wave probe a quarter *guide* wavelength
in front of the short-circuited back wall. Outputs:
  ../cad/horn_params.scad   dimensions for the OpenSCAD model and printable jigs
  ../images/horn-cutting-diagram.svg   full-size (mm) flat patterns of the four flare panels + waveguide
"""
from __future__ import annotations

import argparse
import math
from pathlib import Path

from scipy.optimize import brentq

C = 299_792_458.0
F_HI = 1420.405751768e6
HERE = Path(__file__).resolve().parent


def design(gain_dbi=17.0, a=0.1651, b=0.08255, f=F_HI):
    lam = C / f
    G0 = 10 ** (gain_dbi / 10)

    def eq(chi):
        lhs = (math.sqrt(2 * chi) - b / lam) ** 2 * (2 * chi - 1)
        rhs = (G0 / (2 * math.pi) * math.sqrt(3 / (2 * math.pi)) / math.sqrt(chi) - a / lam) ** 2 * \
              (G0 ** 2 / (6 * math.pi ** 3) / chi - 1)
        return lhs - rhs

    chi1 = G0 / (2 * math.pi * math.sqrt(2 * math.pi))  # Balanis' first guess
    chi = brentq(eq, chi1 * 0.3, chi1 * 3.0)
    rho_e = chi * lam
    rho_h = G0 ** 2 / (8 * math.pi ** 3 * chi) * lam
    a1 = math.sqrt(3 * lam * rho_h)
    b1 = math.sqrt(2 * lam * rho_e)
    pe = (b1 - b) * math.sqrt((rho_e / b1) ** 2 - 0.25)
    ph = (a1 - a) * math.sqrt((rho_h / a1) ** 2 - 0.25)
    # waveguide TE10 cutoff and guide wavelength
    fc10 = C / (2 * a)
    fc20 = C / a
    fc01 = C / (2 * b)
    lam_g = lam / math.sqrt(1 - (lam / (2 * a)) ** 2)
    # radiation: aperture efficiency ~0.51 for an optimum horn; half-power beamwidths (uniform/cosine aperture)
    g_check = 0.51 * 4 * math.pi * a1 * b1 / lam ** 2
    hpbw_e = math.degrees(0.94 * lam / b1)      # E-plane: ~ uniform amplitude, quadratic phase
    hpbw_h = math.degrees(1.36 * lam / a1)      # H-plane: cosine amplitude taper
    return dict(freq_hz=f, lam=lam, gain_dbi=gain_dbi, chi=chi, rho_e=rho_e, rho_h=rho_h, a=a, b=b, a1=a1, b1=b1,
                pe=pe, ph=ph, fc10=fc10, fc20=fc20, fc01=fc01, lam_g=lam_g, gain_check_dbi=10 * math.log10(g_check),
                hpbw_e=hpbw_e, hpbw_h=hpbw_h, probe_len=0.95 * lam / 4, probe_from_back=lam_g / 4,
                guide_len=0.75 * lam_g + lam_g / 4)


def panels(d):
    """Flat patterns (mm). Each flare wall is a trapezoid; its true (slant) height is the length of the
    wall measured along the surface, from the throat edge to the aperture edge."""
    mm = 1000
    a, b, a1, b1, p = d["a"] * mm, d["b"] * mm, d["a1"] * mm, d["b1"] * mm, d["pe"] * mm
    # E-plane walls (top/bottom, width a -> a1): tilted by the E-plane flare (b -> b1)
    slant_top = math.hypot(p, (b1 - b) / 2)
    slant_side = math.hypot(p, (a1 - a) / 2)
    return {
        "top/bottom wall (x2)": (a, a1, slant_top),
        "left/right wall (x2)": (b, b1, slant_side),
    }


def dihedral_deg(d):
    """Interior angle between a broad (top) wall and a narrow (side) wall of the flare."""
    da, db, pe = (d["a1"] - d["a"]) / 2, (d["b1"] - d["b"]) / 2, d["pe"]
    n_top = (0.0, pe, -db)
    n_side = (pe, 0.0, -da)
    dot = sum(x * y for x, y in zip(n_top, n_side))
    cosang = dot / (math.hypot(*n_top) * math.hypot(*n_side))
    return 180.0 - math.degrees(math.acos(cosang))


def write_scad(d):
    mm = 1000
    lines = [f"// generated by tools/horn_design.py for {d['gain_dbi']:.1f} dBi at {d['freq_hz'] / 1e6:.6f} MHz",
             f"corner_angle = {dihedral_deg(d):.2f};  // interior angle between adjacent flare walls"]
    for k in ("a", "b", "a1", "b1", "pe", "lam", "lam_g", "probe_len", "probe_from_back", "guide_len"):
        lines.append(f"{k} = {d[k] * mm:.2f};")
    (HERE.parent / "cad" / "horn_params.scad").write_text("\n".join(lines) + "\n")


def write_svg(d, out):
    """Full-size cutting diagram in millimetres (open in Inkscape, print tiled or transfer by measuring)."""
    mm = 1000
    P = panels(d)
    a, b, lg = d["a"] * mm, d["b"] * mm, d["guide_len"] * mm
    tab = 15
    shapes, y = [], 20
    W = 20 + max(v[1] for v in P.values()) + 40 + 2 * (a + b) + 60
    for name, (w0, w1, h) in P.items():
        x0 = 20
        off = (w1 - w0) / 2
        pts = [(x0 + off, y), (x0 + off + w0, y), (x0 + w1, y + h), (x0, y + h)]
        poly = " ".join(f"{px:.1f},{py:.1f}" for px, py in pts)
        shapes.append(f'<polygon points="{poly}" fill="#e3eefa" stroke="#2a78d6" stroke-width="1"/>')
        # glue tabs along one slanted edge
        tabpts = [pts[1], pts[2], (pts[2][0] + tab, pts[2][1] - tab), (pts[1][0] + tab, pts[1][1] + tab)]
        shapes.append('<polygon points="' + " ".join(f"{px:.1f},{py:.1f}" for px, py in tabpts) +
                      '" fill="none" stroke="#52514e" stroke-dasharray="4 3" stroke-width="0.8"/>')
        shapes.append(f'<text x="{x0 + w1 / 2:.1f}" y="{y + h / 2:.1f}" font-size="14" text-anchor="middle" '
                      f'font-family="sans-serif">{name}</text>')
        shapes.append(f'<text x="{x0 + w1 / 2:.1f}" y="{y + h / 2 + 18:.1f}" font-size="11" text-anchor="middle" '
                      f'font-family="sans-serif">throat {w0:.1f} mm, aperture {w1:.1f} mm, slant height {h:.1f} mm</text>')
        y += h + 40
    # waveguide: one strip folded into a rectangle a x b, length guide_len, plus the back plate
    x0 = 20 + max(v[1] for v in P.values()) + 40
    y0 = 20
    xs = [x0, x0 + b, x0 + b + a, x0 + 2 * b + a, x0 + 2 * (a + b)]
    shapes.append(f'<rect x="{x0}" y="{y0}" width="{2 * (a + b):.1f}" height="{lg:.1f}" fill="#e2f4ec" stroke="#1baf7a"/>')
    for xf in xs[1:-1]:
        shapes.append(f'<line x1="{xf:.1f}" y1="{y0}" x2="{xf:.1f}" y2="{y0 + lg:.1f}" stroke="#1baf7a" stroke-dasharray="6 3"/>')
    shapes.append(f'<text x="{x0 + a + b:.1f}" y="{y0 + lg / 2 - 60:.1f}" font-size="13" text-anchor="middle" font-family="sans-serif">'
                  f'waveguide wrap, fold on the dashed lines</text>')
    shapes.append(f'<text x="{x0 + a + b:.1f}" y="{y0 + lg / 2 - 42:.1f}" font-size="12" text-anchor="middle" font-family="sans-serif">'
                  f'{b:.1f} | {a:.1f} | {b:.1f} | {a:.1f} mm wide, {lg:.1f} mm long</text>')
    shapes.append(f'<text x="{x0 + 5:.1f}" y="{y0 + 14:.1f}" font-size="11" font-family="sans-serif">flare end (open)</text>')
    shapes.append(f'<text x="{x0 + 5:.1f}" y="{y0 + lg - 6:.1f}" font-size="11" font-family="sans-serif">back end (closed by the back plate)</text>')
    px = x0 + b + a / 2
    py = y0 + lg - d["probe_from_back"] * mm
    shapes.append(f'<circle cx="{px:.1f}" cy="{py:.1f}" r="6" fill="none" stroke="#eb6834" stroke-width="2"/>')
    shapes.append(f'<text x="{px:.1f}" y="{py - 12:.1f}" font-size="11" text-anchor="middle" font-family="sans-serif" fill="#c0461b">'
                  f'probe hole, centre of the broad wall,</text>')
    shapes.append(f'<text x="{px:.1f}" y="{py + 20:.1f}" font-size="11" text-anchor="middle" font-family="sans-serif" fill="#c0461b">'
                  f'{d["probe_from_back"] * mm:.1f} mm from the back end</text>')
    shapes.append(f'<rect x="{x0}" y="{y0 + lg + 30:.1f}" width="{a:.1f}" height="{b:.1f}" fill="#e2f4ec" stroke="#1baf7a"/>')
    shapes.append(f'<text x="{x0 + a / 2:.1f}" y="{y0 + lg + 30 + b / 2:.1f}" font-size="12" text-anchor="middle" '
                  f'font-family="sans-serif">back plate {a:.1f} x {b:.1f}</text>')
    H = max(y, y0 + lg + b + 60) + 20
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{W:.0f}mm" height="{H:.0f}mm" viewBox="0 0 {W:.0f} {H:.0f}">'
           f'<rect width="100%" height="100%" fill="white"/>'
           f'<text x="20" y="14" font-size="12" font-family="sans-serif">Hydrogen-line horn, {d["gain_dbi"]:.0f} dBi - full size, units mm. '
           f'Foam board + aluminium tape inside. Dashed = glue tabs / fold lines.</text>' + "".join(shapes) + "</svg>")
    Path(out).write_text(svg)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--gain", type=float, default=17.0, help="design gain, dBi")
    args = ap.parse_args()
    d = design(args.gain)
    mm = 1000
    print(f"frequency {d['freq_hz'] / 1e6:.6f} MHz, free-space wavelength {d['lam'] * mm:.2f} mm")
    print(f"feed WR-650: a = {d['a'] * mm:.2f} mm, b = {d['b'] * mm:.2f} mm")
    print(f"  TE10 cutoff {d['fc10'] / 1e6:.0f} MHz, next modes TE01 {d['fc01'] / 1e6:.0f} MHz / TE20 {d['fc20'] / 1e6:.0f} MHz -> single-mode at 1420 MHz")
    print(f"  guide wavelength {d['lam_g'] * mm:.1f} mm")
    print(f"  probe: {d['probe_len'] * mm:.1f} mm long (lambda/4, -5 %), {d['probe_from_back'] * mm:.1f} mm (lambda_g/4) from the back wall")
    print(f"  waveguide section length {d['guide_len'] * mm:.0f} mm")
    print(f"horn: chi = {d['chi']:.4f}")
    print(f"  aperture a1 x b1 = {d['a1'] * mm:.1f} x {d['b1'] * mm:.1f} mm")
    print(f"  axial length pe = {d['pe'] * mm:.1f} mm, ph = {d['ph'] * mm:.1f} mm (equal -> realisable)")
    print(f"  gain check 0.51 * 4 pi A / lambda^2 = {d['gain_check_dbi']:.2f} dBi")
    print(f"  half-power beamwidth: E-plane {d['hpbw_e']:.1f} deg, H-plane {d['hpbw_h']:.1f} deg")
    print(f"  corner angle between adjacent flare walls: {dihedral_deg(d):.2f} deg")
    for name, (w0, w1, h) in panels(d).items():
        print(f"  flat pattern {name}: {w0:.1f} -> {w1:.1f} mm, slant height {h:.1f} mm")
    write_scad(d)
    write_svg(d, HERE.parent / "images" / "horn-cutting-diagram.svg")
    print("wrote cad/horn_params.scad and images/horn-cutting-diagram.svg")
    return d


if __name__ == "__main__":
    main()
